# ------------------------------------------------------------
# 存在的理由：原管线（train/train.py）是「8 个因子组得分 → 岭回归 → L1 归一权重」，
# 是一条纯线性、8 维、单模型的通路。它有两个结构性上限：
#   1. 线性：dcor 检验反复显示因子与收益存在非线性依赖，线性模型提取不到；
#   2. 一次性：每 6 小时训练一次、闸门拒绝就冻结权重，没有任何搜索/进化过程。
# 本包提供三件原管线缺的东西：
#   A. 真正的非线性模型族（树集成 / MLP / 状态门控）—— models.py + cv.py
#   B. 面向「能否赚钱」而不是「IC 好不好看」的评估 —— pnl.py（净成本）+ stats.py（多重检验）
#   C. 零 token 的自动迭代：进化式搜索 + 防过拟合采纳闸门 —— loop.py
#
# 反过拟合的立场（本包最重要的设计约束）：
#   自动搜索几千个配置后，「最好看的那个」几乎必然是噪声。所以任何候选想被采纳，
#   必须同时通过 ① 净成本 PnL 为正 ② Newey-West t 显著 ③ Deflated Sharpe > 0
#   ④ PBO（回测过拟合概率）低于阈值。少一条都不采纳——宁可发布「静态权重」，
#   也不发布一个被搜出来的幻觉。
